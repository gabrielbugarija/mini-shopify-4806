package org.example;

import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.*;

class ShopTest {

    // Create product objects
    Product product1 = new Product("Concert Tickets", 120.00, 2);
    Product product2 = new Product("Television", 199.99, 1);
    Product product3 = new Product("E-Book", 14.99, 3);

    Shop shop = new Shop("Shop 1", "This shop sells everything");

    @Test
    void addProduct() {
        shop.addProduct(product1);
        shop.addProduct(product2);
        shop.addProduct(product3);

        assertEquals("Concert Tickets", shop.getProducts().get(0).getProductname());
        assertEquals("Television", shop.getProducts().get(1).getProductname());
        assertEquals("E-Book", shop.getProducts().get(2).getProductname());
    }

    @Test
    void removeProduct() {
        shop.addProduct(product1);
        shop.addProduct(product2);
        shop.addProduct(product3);

        shop.removeProduct(product2);
        Product productAtRemovedIndex = shop.getProducts().get(1);

        assertNotEquals("Television", productAtRemovedIndex.getProductname());
        assertNotEquals(199.99, productAtRemovedIndex.getPrice());
        assertNotEquals(1, productAtRemovedIndex.getQuantity());
    }

    @Test
    void addTag() {
        shop.addTag("electronics");
        assertTrue(shop.getTags().contains("electronics"));
    }

    @Test
    void getProducts() {
        assertTrue(shop.getProducts().isEmpty());

        shop.addProduct(product1);

        assertEquals(1, shop.getProducts().size());
        assertEquals(product1, shop.getProducts().get(0));
    }

    @Test
    void getId() {
        // The id is generated by the database, so it is null until the shop is saved
        assertNull(shop.getId());
    }

    @Test
    void getName() {
        assertEquals("Shop 1", shop.getName());
    }

    @Test
    void setName() {
        shop.setName("Shop 2");
        assertEquals("Shop 2", shop.getName());
    }

    @Test
    void getDescription() {
        assertEquals("This shop sells everything", shop.getDescription());
    }

    @Test
    void setDescription() {
        shop.setDescription("This shop sells nothing");

        assertEquals("This shop sells nothing", shop.getDescription());
    }

    @Test
    void getTags() {
        assertTrue(shop.getTags().isEmpty());

        shop.addTag("electronics");
        shop.addTag("books");

        assertEquals(2, shop.getTags().size());
    }
}
